#!/usr/bin/env python3
"""Writes THIRD_PARTY_NOTICES.md: what the CertKeeper image includes from others, with the NOTICE files
and license texts their licenses ask to be passed on.

    swift package resolve && python3 tools/third-party-notices.py

Run it after changing dependencies. SERVER lists the packages that end up in the server; check it by
building it in a fresh scratch path and listing the modules it compiles:

    swift build --product certkeeper-server --scratch-path /tmp/ck
    ls /tmp/ck/out/Intermediates.noindex
"""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CHECKOUTS = os.path.join(ROOT, ".build", "checkouts")

# Swift packages compiled into the server. All are Apache License 2.0.
SERVER = ["swift-certificates", "swift-asn1", "swift-crypto",
    "hummingbird", "swift-nio", "swift-nio-ssl", "swift-nio-extras", "swift-http-types", "swift-log",
    "swift-metrics", "swift-distributed-tracing", "swift-service-context", "swift-service-lifecycle",
    "swift-configuration", "swift-async-algorithms", "swift-collections", "swift-atomics", "swift-system",
]

# Linked into the server's static Linux binary from Swift's static Linux SDK.
C_LIBRARIES = [
    ("musl", "the C library", "MIT", "musl.txt", "https://musl.libc.org"),
    ("libcurl 8.15.0", "HTTP client behind URLSession", "curl license (MIT/X derivative)", "curl.txt", "https://curl.se"),
    ("zlib 1.3.1", "compression, used by libcurl", "zlib license", "zlib.txt", "https://zlib.net"),
    ("ICU 76 and its Unicode data", "used by Foundation", "Unicode License v3, plus the third-party terms in the file",
     "icu.txt", "https://icu.unicode.org"),
    ("mimalloc", "memory allocator", "MIT", "mimalloc.txt", "https://github.com/microsoft/mimalloc"),
]


def resolved_versions():
    with open(os.path.join(ROOT, "Package.resolved")) as f:
        pins = json.load(f)["pins"]
    return {p["identity"]: (p["location"].removesuffix(".git"), p["state"].get("version", p["state"].get("revision", "")[:12]))
            for p in pins}


def read(path):
    with open(path, encoding="utf-8") as f:
        return f.read().strip()


def notice_file(package):
    folder = os.path.join(CHECKOUTS, package)
    for name in sorted(os.listdir(folder)):
        if name.lower().startswith("notice"):
            return os.path.join(folder, name)
    return None


def main():
    versions = resolved_versions()
    out = []
    w = out.append
    w("# Third-party notices\n")
    w("CertKeeper is Copyright 2026 Mike Waters and licensed under the Apache License, Version 2.0 (see")
    w("[LICENSE](LICENSE) and [NOTICE](NOTICE)). It's built on the open-source software below, whose authors")
    w("we thank. This file is generated by `tools/third-party-notices.py`.\n")

    w("## Swift packages\n")
    w("All are licensed under the Apache License, Version 2.0, the same text as CertKeeper's [LICENSE](LICENSE).\n")
    w("| Package | Version |")
    w("|---|---|")
    for package in sorted(set(SERVER)):
        url, version = versions[package]
        w(f"| [{package}]({url}) | {version} |")
    w("")
    w("swift-crypto and swift-nio-ssl each include a copy of [BoringSSL](https://boringssl.googlesource.com/boringssl/)")
    w("(Copyright The OpenSSL Project Authors and Google Inc.), which those copies carry under the Apache License 2.0.")
    w("BoringSSL in turn includes [fiat-crypto](https://github.com/mit-plv/fiat-crypto) (Copyright 2015-2020 the")
    w("fiat-crypto authors, Apache License 2.0) and one public-domain Poly1305 assembly file.\n")

    w("## Swift runtime and toolchain libraries\n")
    w("The Swift standard library, Foundation and Dispatch are licensed under the Apache License 2.0 with the")
    w("Runtime Library Exception, and LLVM's libc++, libc++abi, libunwind and compiler-rt under the Apache License")
    w("2.0 with LLVM Exceptions. Both exceptions waive attribution for compiled code embedded in a program.\n")

    w("## C libraries in the static Linux binary\n")
    w("| Library | Used for | License |")
    w("|---|---|---|")
    for name, use, license_name, _, url in C_LIBRARIES:
        w(f"| [{name}]({url}) | {use} | {license_name} |")
    w("")
    w("The container image is based on Debian (`debian:trixie-slim`) and adds OpenSSH, OpenSSL, curl, tini and")
    w("nss_wrapper from Debian's packages; their copyright files are in the image under `/usr/share/doc`.\n")

    w("## NOTICE files of the Swift packages\n")
    w("Reproduced as the Apache License 2.0 (section 4d) asks.\n")
    for package in sorted(set(SERVER)):
        path = notice_file(package)
        if path:
            w(f"### {package}\n")
            w("```")
            w(read(path))
            w("```\n")

    w("## License texts of the C libraries\n")
    for name, _, _, file, _ in C_LIBRARIES:
        w(f"### {name}\n")
        w("```")
        w(read(os.path.join(ROOT, "licenses", file)))
        w("```\n")

    with open(os.path.join(ROOT, "THIRD_PARTY_NOTICES.md"), "w", encoding="utf-8") as f:
        f.write("\n".join(out))
    print(f"Wrote THIRD_PARTY_NOTICES.md ({len(out)} lines)")


if __name__ == "__main__":
    main()
