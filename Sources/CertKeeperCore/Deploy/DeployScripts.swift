import Foundation

/// Builds the shell scripts that install certificates on hosts.
///
/// Every deploy runs as one `sh -s` session:
///   1. a generated preamble writes the PEMs to a private temp dir and defines variables + helpers
///   2. the template for the deployment kind (or the user's override) does the install
///   3. the temp dir is removed on exit
///
/// Variables available to templates:
///   $CERT $CHAIN $FULLCHAIN $KEY          — temp files holding the new material
///   $TARGET_CERT $TARGET_KEY $TARGET_CHAIN — destination paths from the deployment
///   $CERT_NAME  — a unique, name-safe label (e.g. certkeeper_www_example_com_20260109120000)
///   $CERT_SLUG  — the stable part of CERT_NAME (used to prune older imports)
///   $DOMAINS    — space-separated SANs
///   $STAMP      — timestamp used for backups
///   $CK_OPT_*   — deployment options (see `DeploymentOption`), e.g. $CK_OPT_TRUENAS_APPS
/// Helpers: ck_install SRC DST MODE (backs up DST), ck_rollback, ck_have CMD
public enum DeployScripts {
    public static func template(for kind: DeploymentKind) -> String {
        switch kind {
        case .nginx: nginx
        case .apache: apache
        case .proxmox: proxmox
        case .truenas: truenas
        case .unifiOS: unifi
        case .opnsense: opnsense
        case .pihole: pihole
        case .containerApp: containerApp
        case .custom: custom
        }
    }

    public static func slug(for certificate: ManagedCertificate) -> String {
        let base = certificate.domains.first ?? certificate.name
        let cleaned = base.lowercased().map { $0.isLetter || $0.isNumber ? $0 : "_" }
        return "certkeeper_" + String(cleaned).trimmingCharacters(in: CharacterSet(charactersIn: "_"))
    }

    public static func build(
        deployment: Deployment,
        certificate: ManagedCertificate,
        keyPEM: String,
        now: Date = Date()
    ) throws -> String {
        guard let leaf = certificate.leafPEM, let full = certificate.fullchainPEM else {
            throw DeployError("Certificate \(certificate.name) has not been issued yet")
        }
        let stamp: String = {
            let f = DateFormatter()
            f.locale = Locale(identifier: "en_US_POSIX")
            f.timeZone = TimeZone(identifier: "UTC")
            f.dateFormat = "yyyyMMddHHmmss"
            return f.string(from: now)
        }()
        let slug = slug(for: certificate)
        let body = deployment.scriptOverride ?? template(for: deployment.kind)
        let knownOptions: [DeploymentOption] = [.truenasUI, .truenasApps, .restartTarget, .reloadCommand, .fileOwner, .certFormat, .pfxPassword, .piholeSetDomain, .nginxConf, .nginxPrefix, .unifiDir]
        var optionLines = knownOptions.map { "\($0.envName)=\(shellQuote(deployment.option($0)))" }
        for (key, value) in deployment.options.sorted(by: { $0.key < $1.key })
        where DeploymentOption(rawValue: key) == nil && key.allSatisfy({ $0.isLetter || $0.isNumber || $0 == "_" }) {
            optionLines.append("CK_OPT_\(key.uppercased())=\(shellQuote(value))")
        }

        func heredoc(_ file: String, _ content: String) -> String {
            "cat > \"$CK_DIR/\(file)\" <<'CERTKEEPER_EOF'\n\(content.trimmingCharacters(in: .whitespacesAndNewlines))\nCERTKEEPER_EOF\n"
        }

        return """
        #!/bin/sh
        # Generated by CertKeeper for \(certificate.name) → \(deployment.kind.displayName)
        set -eu
        umask 077
        CK_DIR=$(mktemp -d "${TMPDIR:-/tmp}/certkeeper.XXXXXX")
        trap 'rm -rf "$CK_DIR"' EXIT
        \(heredoc("cert.pem", leaf))\(heredoc("chain.pem", certificate.chainPEM ?? ""))\(heredoc("fullchain.pem", full))\(heredoc("key.pem", keyPEM))
        CERT="$CK_DIR/cert.pem"; CHAIN="$CK_DIR/chain.pem"; FULLCHAIN="$CK_DIR/fullchain.pem"; KEY="$CK_DIR/key.pem"
        TARGET_CERT=\(shellQuote(deployment.certPath))
        TARGET_KEY=\(shellQuote(deployment.keyPath))
        TARGET_CHAIN=\(shellQuote(deployment.chainPath))
        DOMAINS=\(shellQuote(certificate.domains.joined(separator: " ")))
        STAMP=\(stamp)
        CERT_SLUG=\(shellQuote(slug))
        CERT_NAME="${CERT_SLUG}_${STAMP}"
        \(optionLines.joined(separator: "\n"))
        export \(knownOptions.map(\.envName).joined(separator: " "))
        CK_BACKUPS=""; CK_NEW=""

        ck_have() { command -v "$1" >/dev/null 2>&1; }

        # ck_install SRC DST MODE — replace DST's contents in place (keeping its owner, mode and ACL)
        # after backing it up. Never needs to change permissions on an existing file, so it also works
        # on ACL-managed datasets (e.g. TrueNAS SMB shares) where chmod is refused even for root.
        # Backups sit next to the file, or in $CK_BACKUP_DIR when a template sets it (e.g. when the
        # folder belongs to a container that chowns everything in it at startup).
        ck_bak() {
          if [ -n "${CK_BACKUP_DIR:-}" ]; then
            mkdir -p "$CK_BACKUP_DIR" && chmod 700 "$CK_BACKUP_DIR"
            printf '%s/%s' "$CK_BACKUP_DIR" "$(printf '%s' "$1" | tr / _)"
          else
            printf '%s' "$1"
          fi
        }

        ck_install() {
          [ -n "$2" ] || return 0
          if [ -f "$2" ]; then
            # Plain copy: the backup is root-only where modes apply (umask 077) or inherits the directory's ACL.
            cat "$2" > "$(ck_bak "$2").certkeeper-$STAMP.bak"
            CK_BACKUPS="$CK_BACKUPS $2"
            cat "$1" > "$2"
            # keep the three newest backups
            ls -1t "$(ck_bak "$2")".certkeeper-*.bak 2>/dev/null | tail -n +4 | while read -r old; do rm -f "$old"; done
          else
            mkdir -p "$(dirname "$2")"
            cat "$1" > "$2"
            chmod "$3" "$2" 2>/dev/null || echo "note: could not chmod $2 (permissions are ACL-managed)" >&2
            CK_NEW="$CK_NEW $2"
          fi
          if [ -n "$CK_OPT_FILE_OWNER" ]; then
            chown "$CK_OPT_FILE_OWNER" "$2" 2>/dev/null || echo "note: could not chown $2 to $CK_OPT_FILE_OWNER" >&2
          fi
          echo "installed $2"
        }

        # midclt's "wait for job" flag changed from -job (older TrueNAS) to -j/--job; ask it which it takes.
        ck_midclt_job_flag() {
          [ -n "${CK_JOB_FLAG:-}" ] && return 0
          ck_h=$(midclt call --help 2>&1 || true)
          if printf '%s\n' "$ck_h" | grep -qE '(^|[^-[:alnum:]])-job([^[:alnum:]]|$)'; then CK_JOB_FLAG=-job
          elif printf '%s\n' "$ck_h" | grep -q -- '--job'; then CK_JOB_FLAG=--job
          else CK_JOB_FLAG=-j; fi
          export CK_JOB_FLAG
        }
        ck_midclt_job() { ck_midclt_job_flag; midclt call "$CK_JOB_FLAG" "$@"; }

        ck_rollback() {
          for f in $CK_BACKUPS; do cat "$(ck_bak "$f").certkeeper-$STAMP.bak" > "$f" && rm -f "$(ck_bak "$f").certkeeper-$STAMP.bak"; echo "restored $f" >&2; done
          for f in $CK_NEW; do rm -f "$f"; done
        }

        # ---- deployment template ----
        \(body)
        """
    }

    // MARK: - Templates

    static let nginx = #"""
    [ -n "$TARGET_CERT" ] && [ -n "$TARGET_KEY" ] || { echo "certPath and keyPath are required" >&2; exit 1; }
    if [ -n "$TARGET_CHAIN" ]; then
      ck_install "$CERT" "$TARGET_CERT" 644
      ck_install "$CHAIN" "$TARGET_CHAIN" 644
    else
      ck_install "$FULLCHAIN" "$TARGET_CERT" 644
    fi
    ck_install "$KEY" "$TARGET_KEY" 600

    # A separate nginx instance (own -p/-c, e.g. a KVM's web UI) is tested and reloaded on its own.
    NGX_ARGS=""
    [ -n "$CK_OPT_NGINX_PREFIX" ] && NGX_ARGS="-p $CK_OPT_NGINX_PREFIX"
    [ -n "$CK_OPT_NGINX_CONF" ] && NGX_ARGS="$NGX_ARGS -c $CK_OPT_NGINX_CONF"
    if ! nginx $NGX_ARGS -t 2>&1; then
      echo "nginx -t failed; rolling back" >&2
      ck_rollback
      exit 1
    fi
    if [ -n "$CK_OPT_NGINX_CONF" ]; then
      NGX_PID=""
      for f in "${CK_PROC:-/proc}"/[0-9]*/cmdline; do
        [ -r "$f" ] || continue
        case " $(tr '\0' ' ' < "$f") " in
          *"nginx: master process"*" -c $CK_OPT_NGINX_CONF "*) NGX_PID=$(basename "$(dirname "$f")"); break ;;
        esac
      done
      [ -n "$NGX_PID" ] || { echo "no running nginx master uses $CK_OPT_NGINX_CONF; files installed but not reloaded" >&2; exit 1; }
      kill -HUP "$NGX_PID"
      echo "nginx reloaded ($CK_OPT_NGINX_CONF, master pid $NGX_PID)"
      exit 0
    fi
    if ck_have systemctl && systemctl is-active --quiet nginx; then
      systemctl reload nginx
    elif ck_have service; then
      service nginx reload
    else
      nginx -s reload
    fi
    echo "nginx reloaded"
    """#

    static let apache = #"""
    [ -n "$TARGET_CERT" ] || { echo "certPath is required" >&2; exit 1; }
    APACHECTL=$(command -v apachectl || command -v apache2ctl || echo apachectl)
    if [ -n "$TARGET_CHAIN" ]; then
      ck_install "$CERT" "$TARGET_CERT" 644
      ck_install "$CHAIN" "$TARGET_CHAIN" 644
    else
      # Apache ≥ 2.4.8 reads the intermediate chain from SSLCertificateFile
      ck_install "$FULLCHAIN" "$TARGET_CERT" 644
    fi
    ck_install "$KEY" "$TARGET_KEY" 600

    if ! "$APACHECTL" -t 2>&1; then
      echo "apache config test failed; rolling back" >&2
      ck_rollback
      exit 1
    fi
    if ck_have systemctl && systemctl is-active --quiet apache2; then
      systemctl reload apache2
    elif ck_have systemctl && systemctl is-active --quiet httpd; then
      systemctl reload httpd
    else
      "$APACHECTL" -k graceful
    fi
    echo "apache reloaded"
    """#

    static let proxmox = #"""
    # Installs as the node's custom pveproxy certificate (does not touch the cluster CA).
    if ck_have pvenode; then
      pvenode cert set "$FULLCHAIN" "$KEY" --force 1 --restart 1
    else
      ck_install "$FULLCHAIN" /etc/pve/local/pveproxy-ssl.pem 640
      ck_install "$KEY" /etc/pve/local/pveproxy-ssl.key 640
      systemctl restart pveproxy
    fi
    echo "pveproxy certificate updated"
    """#

    static let truenas = #"""
    # TrueNAS SCALE / Community Edition (apps: 24.10+).
    #  1. imports the certificate (a new entry per renewal — TrueNAS can't replace an imported cert in place)
    #  2. makes it the web UI certificate             (option: truenas_ui)
    #  3. repoints catalog apps that use an older CertKeeper import of this certificate,
    #     plus any apps named in the truenas_apps option, and redeploys them
    #  4. deletes older CertKeeper imports only if nothing (UI or any app) still references them;
    #     TrueNAS also refuses to delete certificates used by other services
    ck_have midclt || { echo "midclt not found — is this TrueNAS SCALE/Community Edition?" >&2; exit 1; }
    ck_midclt_job_flag
    CK_CERT_NAME="$CERT_NAME" CK_CERT_SLUG="$CERT_SLUG" CK_FULLCHAIN="$FULLCHAIN" CK_KEY="$KEY" CK_DIR="$CK_DIR" python3 - <<'PY'
    import json, os, subprocess, sys

    def mid(*args, job=False):
        cmd = ["midclt", "call"] + ([os.environ["CK_JOB_FLAG"]] if job else []) + [a if isinstance(a, str) else json.dumps(a) for a in args]
        p = subprocess.run(cmd, capture_output=True, text=True)
        if p.returncode != 0:
            raise RuntimeError("%s %s failed: %s" % (args[0], "(job)" if job else "", (p.stderr or p.stdout).strip()[-800:]))
        try:
            return json.loads(p.stdout)
        except ValueError:
            return p.stdout.strip()

    def cert_refs(node, fn):
        """Calls fn(container, key) for every certificate_id field in an app config."""
        if isinstance(node, dict):
            for k, v in list(node.items()):
                if k == "certificate_id":
                    fn(node, k)
                else:
                    cert_refs(v, fn)
        elif isinstance(node, list):
            for v in node:
                cert_refs(v, fn)

    def query_apps():
        try:
            return mid("app.query", [], {"extra": {"retrieve_config": True}})
        except RuntimeError as e:
            if named_apps:
                raise
            print("note: app query unavailable (%s)" % e)
            return []

    name, slug = os.environ["CK_CERT_NAME"], os.environ["CK_CERT_SLUG"]
    set_ui = os.environ.get("CK_OPT_TRUENAS_UI", "true") == "true"
    named_apps = [a.strip() for a in os.environ.get("CK_OPT_TRUENAS_APPS", "").split(",") if a.strip()]
    problems = []

    mid("certificate.create", {
        "name": name,
        "create_type": "CERTIFICATE_CREATE_IMPORTED",
        "certificate": open(os.environ["CK_FULLCHAIN"]).read(),
        "privatekey": open(os.environ["CK_KEY"]).read(),
    }, job=True)
    new_id = mid("certificate.query", [["name", "=", name]], {"get": True})["id"]
    print("imported certificate %s (id %s)" % (name, new_id))
    old_ids = {c["id"] for c in mid("certificate.query", [["name", "^", slug + "_"]]) if c["id"] != new_id}

    if set_ui:
        ui = mid("system.general.config").get("ui_certificate")
        ui_id = ui.get("id") if isinstance(ui, dict) else ui
        if ui_id != new_id:
            mid("system.general.update", {"ui_certificate": new_id})
            open(os.path.join(os.environ["CK_DIR"], "restart_ui"), "w").close()
            print("web UI now uses id %s" % new_id)

    apps = query_apps()
    for wanted in named_apps:
        if not any(a["name"] == wanted for a in apps):
            problems.append("app %s not found" % wanted)
    for app in apps:
        cfg = app.get("config") or {}
        named = app["name"] in named_apps
        changed, fields = [], []
        def repoint(node, key):
            fields.append(key)
            current = node[key]
            if current in old_ids or (named and current != new_id):
                node[key] = new_id
                changed.append(current)
        cert_refs(cfg, repoint)
        if named and not fields:
            problems.append("app %s has no certificate setting" % app["name"])
        if changed:
            try:
                mid("app.update", app["name"], {"values": cfg}, job=True)
                print("app %s: certificate %s -> %s" % (app["name"], ",".join(map(str, changed)), new_id))
            except RuntimeError as e:
                problems.append("app %s: %s" % (app["name"], e))

    # Only delete what nothing references any more (re-read: updates above may have failed).
    refs = set()
    ui = mid("system.general.config").get("ui_certificate")
    refs.add(ui.get("id") if isinstance(ui, dict) else ui)
    for app in query_apps():
        cert_refs(app.get("config") or {}, lambda node, key: refs.add(node[key]))
    for old in sorted(old_ids):
        if old in refs:
            print("kept certificate %s (still in use)" % old)
            continue
        try:
            mid("certificate.delete", old, job=True)
            print("removed old certificate %s" % old)
        except RuntimeError as e:
            print("kept certificate %s (%s)" % (old, str(e).splitlines()[-1] if str(e) else "delete refused"))

    if problems:
        sys.exit("; ".join(problems))
    PY
    if [ -f "$CK_DIR/restart_ui" ]; then
      # Restart the UI last and detached — this drops existing web sessions.
      (sleep 2; midclt call system.general.ui_restart >/dev/null 2>&1) >/dev/null 2>&1 &
      echo "web UI restart scheduled"
    fi
    """#

    static let unifi = #"""
    # UniFi OS consoles (UDM/UCG/UNVR/CloudKey Gen2+) keep the web certificate in /data/unifi-core/config.
    # UniFi OS Server runs UniFi OS in a podman container (rootless, as user uosserver) with the same
    # files in its data volume. Discovery records the folder in $CK_OPT_UNIFI_DIR.
    UNIFI_DIR="$CK_OPT_UNIFI_DIR"
    if [ -z "$UNIFI_DIR" ]; then
      for d in "${CK_ROOT:-}"/data/unifi-core/config "${CK_ROOT:-}"/mnt/data/unifi-core/config \
               "${CK_ROOT:-}"/home/*/.local/share/containers/storage/volumes/*/_data/unifi-core/config \
               "${CK_ROOT:-}"/var/lib/containers/storage/volumes/*/_data/unifi-core/config \
               $(find "${CK_ROOT:-}"/data "${CK_ROOT:-}"/mnt "${CK_ROOT:-}"/var/lib "${CK_ROOT:-}"/opt "${CK_ROOT:-}"/srv \
                   -maxdepth 6 -type f -name unifi-core.crt 2>/dev/null | head -n 5 | xargs -n1 dirname 2>/dev/null); do
        if [ -f "$d/unifi-core.crt" ]; then UNIFI_DIR=$d; break; fi
      done
    fi
    [ -n "$UNIFI_DIR" ] && [ -f "$UNIFI_DIR/unifi-core.crt" ] || { echo "Could not find unifi-core.crt (looked in ${UNIFI_DIR:-the usual places})" >&2; exit 1; }
    echo "using $UNIFI_DIR"
    # UniFi OS Server's startup chowns everything in this folder and fails on root-owned files, so
    # keep CertKeeper's backups on the host instead.
    case "$UNIFI_DIR" in */containers/storage/volumes/*) CK_BACKUP_DIR="${CK_ROOT:-}/var/backups/certkeeper" ;; esac
    # In-place writes keep the files' owner — inside the container that's unifi-core's (sub)uid.
    ck_install "$FULLCHAIN" "$UNIFI_DIR/unifi-core.crt" 644
    ck_install "$KEY" "$UNIFI_DIR/unifi-core.key" 600

    case "$UNIFI_DIR" in
      */containers/storage/volumes/*)
        # UniFi OS Server: restart unifi-core inside the container (quick); if that isn't possible,
        # restart the whole uosserver service (slower, always works).
        case "$UNIFI_DIR" in
          */.local/share/containers/*)
            PODMAN_HOME=${UNIFI_DIR%%/.local/share/containers/*}
            PODMAN_USER=$(stat -c %U "$PODMAN_HOME" 2>/dev/null || stat -f %Su "$PODMAN_HOME") ;;
          *) PODMAN_USER=root ;;
        esac
        uos_podman() {
          if [ "$PODMAN_USER" = root ]; then podman "$@"
          else (cd / && runuser -u "$PODMAN_USER" -- env XDG_RUNTIME_DIR="/run/user/$(id -u "$PODMAN_USER")" podman "$@"); fi
        }
        if uos_podman exec uosserver systemctl restart unifi-core >/dev/null 2>&1; then
          echo "restarted unifi-core inside the uosserver container"
        elif ck_have systemctl && systemctl cat uosserver.service >/dev/null 2>&1; then
          systemctl restart uosserver
          echo "restarted the uosserver service (UniFi OS Server); the UI may take a minute to return"
        else
          echo "Installed, but could not restart UniFi OS Server — restart the uosserver service manually." >&2
          exit 1
        fi
        ;;
      *)
        if ck_have systemctl && systemctl list-unit-files 2>/dev/null | grep -q '^unifi-core'; then
          systemctl restart unifi-core
        elif ck_have unifi-os; then
          unifi-os restart
        else
          echo "Installed, but could not determine how to restart unifi-core — restart it manually." >&2
          exit 1
        fi
        echo "unifi-core restarted"
        ;;
    esac
    """#

    static let opnsense = #"""
    # OPNsense: imports into System › Trust › Certificates (updating CertKeeper's previous entry with
    # the same description, so its refid and anything referencing it stay valid), points the web GUI
    # at it, then checks the result through OPNsense's own certificate model before restarting the
    # GUI. Any mismatch restores the config.xml backup and stops with the GUI untouched.
    OPN_PHP=/usr/local/bin/php
    [ -x "$OPN_PHP" ] || OPN_PHP=php
    BACKUP="/conf/config.xml.certkeeper-$STAMP.bak"
    cp -p /conf/config.xml "$BACKUP"
    ls -1t /conf/config.xml.certkeeper-*.bak 2>/dev/null | tail -n +4 | while read -r old; do rm -f "$old"; done
    REFID_FILE="$CK_DIR/refid"

    CK_DESCR="$CERT_SLUG" CK_FULLCHAIN="$FULLCHAIN" CK_KEY="$KEY" CK_REFID_FILE="$REFID_FILE" "$OPN_PHP" <<'PHP'
    <?php
    require_once('config.inc');
    require_once('util.inc');
    global $config;

    function ck_uuid() {
        $b = random_bytes(16);
        $b[6] = chr((ord($b[6]) & 0x0f) | 0x40);
        $b[8] = chr((ord($b[8]) & 0x3f) | 0x80);
        $h = bin2hex($b);
        return substr($h, 0, 8) . '-' . substr($h, 8, 4) . '-' . substr($h, 12, 4) . '-' . substr($h, 16, 4) . '-' . substr($h, 20);
    }

    $descr = getenv('CK_DESCR');
    $crt = base64_encode(file_get_contents(getenv('CK_FULLCHAIN')));
    $prv = base64_encode(file_get_contents(getenv('CK_KEY')));
    if (!isset($config['cert']) || !is_array($config['cert'])) { $config['cert'] = []; }
    if (isset($config['cert']['refid'])) { $config['cert'] = [$config['cert']]; }

    $refid = null;
    $othersHaveUUID = false;
    foreach ($config['cert'] as $i => $c) {
        if (!empty($c['@attributes']['uuid'])) { $othersHaveUUID = true; }
        if (($c['descr'] ?? '') === $descr) {
            $refid = $c['refid'];
            $config['cert'][$i]['crt'] = $crt;
            $config['cert'][$i]['prv'] = $prv;
        }
    }
    if ($refid === null) {
        $refid = uniqid();
        $entry = ['refid' => $refid, 'descr' => $descr, 'crt' => $crt, 'prv' => $prv];
        // Match the existing entries: since 24.7 the Trust model keys certificates by uuid.
        if ($othersHaveUUID) { $entry = ['@attributes' => ['uuid' => ck_uuid()]] + $entry; }
        $config['cert'][] = $entry;
    }
    $config['system']['webgui']['ssl-certref'] = $refid;
    write_config("CertKeeper installed certificate {$descr}");
    file_put_contents(getenv('CK_REFID_FILE'), $refid);
    echo "imported {$descr} (refid {$refid})\n";
    PHP

    # Fresh process: read it back the way the GUI will, through the Trust model and the saved config.
    if ! CK_REFID="$(cat "$REFID_FILE")" CK_FULLCHAIN="$FULLCHAIN" "$OPN_PHP" <<'PHP'
    <?php
    require_once('config.inc');
    $refid = getenv('CK_REFID');
    $want = base64_encode(file_get_contents(getenv('CK_FULLCHAIN')));
    $problems = [];
    $cfg = OPNsense\Core\Config::getInstance()->object();
    if ((string)$cfg->system->webgui->{'ssl-certref'} !== $refid) { $problems[] = 'web GUI does not point at the new certificate'; }
    $found = false;
    $mdl = new OPNsense\Trust\Cert();
    foreach ($mdl->cert->iterateItems() as $uuid => $node) {
        if ((string)$node->refid !== $refid) { continue; }
        $found = true;
        if ((string)$node->crt !== $want) { $problems[] = 'stored certificate differs from the one sent'; }
        if (strlen((string)$uuid) < 32) { $problems[] = 'certificate entry has no uuid'; }
    }
    if (!$found) { $problems[] = "Trust model has no certificate with refid {$refid}"; }
    if ($problems) { fwrite(STDERR, 'verification failed: ' . implode('; ', $problems) . "\n"); exit(1); }
    echo "verified: Trust model has the certificate and the web GUI uses it\n";
    PHP
    then
      cp -p "$BACKUP" /conf/config.xml
      echo "restored /conf/config.xml from $BACKUP; web GUI not restarted" >&2
      exit 1
    fi

    configctl webgui restart
    echo "web GUI restarted"
    """#

    static let pihole = #"""
    # Pi-hole v6: pihole-FTL's web server reads one PEM file with the private key and the certificate
    # chain (webserver.tls.cert, default /etc/pihole/tls.pem). For a Docker install, set the restart
    # target to the container name and the TLS file to its host path.
    TLS="${TARGET_CERT:-/etc/pihole/tls.pem}"
    C="$CK_OPT_RESTART_TARGET"
    ftl() { if [ -n "$C" ]; then docker exec "$C" pihole-FTL "$@"; else pihole-FTL "$@"; fi; }

    cat "$KEY" "$FULLCHAIN" > "$CK_DIR/tls.pem"
    PH_NEW=0; [ -f "$TLS" ] || PH_NEW=1
    ck_install "$CK_DIR/tls.pem" "$TLS" 600
    # FTL runs as the pihole user and must be able to read a newly created file
    if [ "$PH_NEW" = 1 ] && [ -z "$C" ] && [ -z "$CK_OPT_FILE_OWNER" ] && id pihole >/dev/null 2>&1; then
      chown pihole:pihole "$TLS"
    fi

    if [ "$CK_OPT_PIHOLE_SET_DOMAIN" = true ]; then
      D=${DOMAINS%% *}
      case "$D" in
        '*.'*) echo "note: first name is a wildcard; webserver.domain left unchanged" ;;
        *) if ftl --config webserver.domain "$D" >/dev/null 2>&1; then echo "webserver.domain set to $D"
           else echo "note: could not set webserver.domain (set by FTLCONF_ environment?)" >&2; fi ;;
      esac
    fi

    if [ -n "$C" ]; then
      docker restart "$C" >/dev/null
      echo "restarted container $C"
    elif ck_have systemctl; then
      systemctl restart pihole-FTL
      echo "restarted pihole-FTL"
    else
      service pihole-FTL restart
      echo "restarted pihole-FTL"
    fi
    """#

    static let containerApp = #"""
    # Certificate files mounted into a container — a TrueNAS custom app, a Docker Compose stack,
    # or a plain container. Put the paths on a dataset/volume the container mounts. Set file
    # owner (e.g. 568:568 for the TrueNAS "apps" user) if the container doesn't run as root.
    # Format pkcs12 writes one .pfx (certificate + chain + key) to the certificate path, e.g. for Jellyfin.
    if [ "$CK_OPT_CERT_FORMAT" = pkcs12 ]; then
      [ -n "$TARGET_CERT" ] || { echo "certPath is required" >&2; exit 1; }
      if [ -n "$CK_OPT_PFX_PASSWORD" ]; then PASSOUT=env:CK_OPT_PFX_PASSWORD; else PASSOUT=pass:; fi
      openssl pkcs12 -export -out "$CK_DIR/cert.pfx" -inkey "$KEY" -in "$FULLCHAIN" -passout "$PASSOUT"
      ck_install "$CK_DIR/cert.pfx" "$TARGET_CERT" 600
    else
    [ -n "$TARGET_CERT" ] && [ -n "$TARGET_KEY" ] || { echo "certPath and keyPath are required" >&2; exit 1; }
    if [ -n "$TARGET_CHAIN" ]; then
      ck_install "$CERT" "$TARGET_CERT" 644
      ck_install "$CHAIN" "$TARGET_CHAIN" 644
    else
      ck_install "$FULLCHAIN" "$TARGET_CERT" 644
    fi
    ck_install "$KEY" "$TARGET_KEY" 600
    fi

    T="$CK_OPT_RESTART_TARGET"
    if [ -n "$CK_OPT_RELOAD_COMMAND" ]; then
      sh -c "$CK_OPT_RELOAD_COMMAND"
      echo "ran reload command"
    elif [ -z "$T" ]; then
      echo "files installed; no restart target configured"
    elif [ "${T#systemd:}" != "$T" ] || [ "${T%.service}" != "$T" ]; then
      U=${T#systemd:}
      systemctl restart "$U"
      echo "restarted $U"
    elif ck_have midclt && midclt call app.query "[[\"name\",\"=\",\"$T\"]]" 2>/dev/null | grep -q '"name"'; then
      ck_midclt_job app.redeploy "$T" >/dev/null
      echo "redeployed TrueNAS app $T"
    elif ck_have docker && docker inspect --type container "$T" >/dev/null 2>&1; then
      docker restart "$T" >/dev/null
      echo "restarted container $T"
    elif ck_have docker && [ -n "$(docker compose -p "$T" ps -q 2>/dev/null)" ]; then
      docker compose -p "$T" restart
      echo "restarted compose project $T"
    else
      echo "restart target '$T' is not a TrueNAS app, container or compose project" >&2
      exit 1
    fi
    """#

